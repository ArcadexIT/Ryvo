/** Builds the flag emoji for an ISO 3166-1 alpha-2 country code (e.g. "BD" -> "🇧🇩"). */
export function flagEmoji(alpha2: string): string {
  return alpha2
    .toUpperCase()
    .replace(/./g, (char) => String.fromCodePoint(0x1f1e6 + char.charCodeAt(0) - 65));
}
